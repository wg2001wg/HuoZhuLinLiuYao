def LIUQIN(my,b):
    mi,bi = WUX[my], WUX[b]
    if mi==bi: return '兄弟'
    if sheng(bi)==mi: return '父母'
    if sheng(mi)==bi: return '子孙'
    if ke(bi)==mi: return '官鬼'
    if ke(mi)==bi: return '妻财'
    return '?'

LIUSHEN_ORDER = ['青龙','朱雀','勾陈','螣蛇','白虎','玄武']
def liushen_start(gan):
    return {'甲':0,'乙':0,'丙':1,'丁':1,'戊':2,'己':3,'庚':4,'辛':4,'壬':5,'癸':5}[gan]

def find_hex(lines):  # lines 自下而上 6
    low = lines[0:3]; up = lines[3:6]
    lname = next(n for n,t in TRI.items() if t[0]==low)
    uname = next(n for n,t in TRI.items() if t[0]==up)
    return next(h for h in HEX if h[1]==uname and h[2]==lname)

def plate(name, lines, moving, palace, day_gan, day_zhi, month_zhi):
    _,up,low,_,_ = next(h for h in HEX if h[0]==name)
    shi = SHIXI[next(h[4] for h in HEX if h[0]==name)] - 1
    ying = (shi+3)%6
    ss = liushen_start(day_gan)
    out=[]
    for p in range(6):
        inner = p<3
        tname = low if inner else up
        trig = TRI[tname]
        dz = trig[4][p] if inner else trig[5][p-3]
        tg = trig[2] if inner else trig[3]
        lq = LIUQIN(TRI[palace][1], WUX_from_dz(dz))
        ls = LIUSHEN_ORDER[(ss+p)%6]
        sy = '世' if p==shi else '应' if p==ying else ''
        out.append((p, ('初' if p==0 else '上' if p==5 else ['二','三','四','五'][p-1])+('九' if lines[p] else '六'),
                    ls, lq, dz, tg, sy, moving[p]))
    return out

